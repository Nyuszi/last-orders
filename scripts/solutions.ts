// Precomputes a proven solution for each handmade night, for the "Show me how" button.
// Usage: npm run solutions   (writes src/solutions.ts)
// On a night with a bonus (peanuts, cards) the lesson plays the combo: the pour that earns the
// bonus and serves a drink at once, then the rest of the night solved from there.
import { writeFileSync } from 'node:fs';
import { LEVELS } from '../src/levels';
import { bonusKinds, findCombo, findSolution, replay } from '../src/solver';

const out: Record<string, unknown> = {};
for (const level of LEVELS) {
  const sol = findSolution(level, { robustNeeded: 1, maxSimsPerOrder: 20000 });
  if (!sol || replay(level, sol.shots).status !== 'won') throw new Error(`No solution for ${level.title}`);
  let shots = sol.shots;
  let from = 0; // a second combo comes after the first, so it doesn't replace it
  for (const kind of bonusKinds(level)) {
    const combo = findCombo(level, shots, kind, { robustNeeded: 2, from, clean: true });
    if (!combo) { console.log(level.id, `no combo for the ${kind}`); continue; }
    const withCombo = findSolution(level, { robustNeeded: 1, maxSimsPerOrder: 20000, prefix: [...shots.slice(0, combo.order), combo.shot] });
    if (withCombo && replay(level, withCombo.shots).status === 'won') {
      shots = withCombo.shots;
      from = combo.order + 1;
      console.log(level.id, `${kind} combo on pour ${combo.order + 1}`);
    } else console.log(level.id, `${kind} combo found, but the night couldn't be finished after it`);
  }
  const check = replay(level, shots);
  if (check.status !== 'won') throw new Error(`${level.title}: solution does not win`);
  out[level.id] = shots.map((s) => ({ ...s, angle: Number(s.angle.toFixed(6)), power: Number(s.power.toFixed(6)) }));
  // The rounded pours must still win (they're what ships).
  if (replay(level, out[level.id] as typeof shots).status !== 'won') throw new Error(`${level.title}: rounded solution does not win`);
  console.log(level.id, 'ok', [...check.badges].join(', '));
}
writeFileSync(new URL('../src/solutions.ts', import.meta.url),
  `// Generated by scripts/solutions.ts. Do not edit by hand.\nimport type { Shot } from './sim';\n\nexport const SOLUTIONS: Record<string, Shot[]> = ${JSON.stringify(out, null, 2)};\n`);
