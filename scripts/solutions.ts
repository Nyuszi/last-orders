// Precomputes a proven solution for each handmade night, for the "Show me how" button.
// Usage: npm run solutions   (writes src/solutions.ts)
import { writeFileSync } from 'node:fs';
import { LEVELS } from '../src/levels';
import { findSolution, replay } from '../src/solver';

const out: Record<string, unknown> = {};
for (const level of LEVELS) {
  const sol = findSolution(level, { robustNeeded: 1, maxSimsPerOrder: 20000 });
  if (!sol || replay(level, sol.shots).status !== 'won') throw new Error(`No solution for ${level.title}`);
  out[level.id] = sol.shots.map((s) => ({ ...s, angle: Number(s.angle.toFixed(6)), power: Number(s.power.toFixed(6)) }));
  console.log(level.id, 'ok');
}
writeFileSync(new URL('../src/solutions.ts', import.meta.url),
  `// Generated by scripts/solutions.ts. Do not edit by hand.\nimport type { Shot } from './sim';\n\nexport const SOLUTIONS: Record<string, Shot[]> = ${JSON.stringify(out, null, 2)};\n`);
